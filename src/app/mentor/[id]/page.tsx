import { getMentorById, MENTORS } from "@/data/mentors";
import { MentorStudioView } from "@/components/studio/MentorStudioView";
import type { MentorConfig } from "@/types/mentor";

interface MentorPageProps {
  params: Promise<{ id: string }>;
  searchParams: Promise<{
    name?: string;
    role?: string;
    subject?: string;
    persona?: string;
    color?: string;
    riv?: string;
    demo?: string;
    test?: string;
  }>;
}

export function generateStaticParams() {
  return MENTORS.map((m) => ({ id: m.id }));
}

export default async function MentorPage({ params, searchParams }: MentorPageProps) {
  const { id } = await params;
  const query = await searchParams;

  const existingMentor = getMentorById(id);

  const customSubject =
    query.subject || existingMentor?.subject || "Custom AI & Computer Science";
  const customName = query.name || existingMentor?.name || "My Custom Mentor";
  const customRole =
    query.role || existingMentor?.roleTitle || "Personal AI Mentor";
  const customColor = query.color || existingMentor?.accentColor || "#38bdf8";
  const customRiv =
    query.riv || existingMentor?.rivFile || "/riv/default-mentor.riv";

  const mentor: MentorConfig = existingMentor
    ? {
        ...existingMentor,
        ...(query.name ? { name: query.name } : {}),
        ...(query.role ? { roleTitle: query.role } : {}),
        ...(query.subject ? { subject: query.subject } : {}),
        ...(query.color ? { accentColor: query.color } : {}),
        ...(query.riv ? { rivFile: query.riv } : {}),
      }
    : {
        id,
        name: customName,
        roleTitle: customRole,
        subject: customSubject,
        shortTag: customSubject.slice(0, 18),
        description: `An autonomous AI mentor tailored to ${customSubject} — featuring live skill diagnosis, Gemini 4 Argon 3D model previews, adaptive quizzes, and Candy rewards.`,
        accentColor: customColor,
        secondaryColor: "#6366f1",
        rivFile: customRiv,
        ring: 0,
        systemPersona:
          query.persona ||
          `You are ${customName} (${customRole}). Your specialty is "${customSubject}". Autonomously diagnose the student's level, explain concepts clearly in English, generate interactive 3D visualizations with Gemini 4 Argon, and reward Candy through quizzes.`,
        starterPrompts: [
          `Diagnose my current level in ${customSubject} with a quick warm-up!`,
          `Generate an interactive 3D model preview of the core architecture in ${customSubject}`,
          `Give me a Candy-rewarded quiz on ${customSubject} fundamentals!`,
        ],
        defaultScene3d: MENTORS[0]?.defaultScene3d || {
          title: `${customSubject} — 3D Concept Architecture`,
          conceptSummary: `Interactive 3D preview illustrating core nodes and data flow in ${customSubject}`,
          mode: "structured_nodes",
          cameraPosition: [0, 2, 7],
          nodes: [
            {
              id: "core",
              label: customSubject,
              shape: "sphere",
              position: [0, 0, 0],
              scale: [1.3, 1.3, 1.3],
              color: customColor,
              animation: "pulse",
              tooltip: `Core concept hub for ${customSubject}`,
            },
            {
              id: "pillar-1",
              label: "Foundations & Input",
              shape: "box",
              position: [-2.4, 0.8, 0],
              scale: [0.9, 0.9, 0.9],
              color: "#6366f1",
              animation: "float",
              tooltip: "Skill assessment & foundational principles",
            },
            {
              id: "pillar-2",
              label: "3D Spatial Intuition",
              shape: "torus",
              position: [2.4, 0.8, 0],
              scale: [0.9, 0.9, 0.9],
              color: "#34d399",
              animation: "rotate",
              tooltip: "Interactive 3D geometry generated by Gemini 4 Argon",
            },
            {
              id: "pillar-3",
              label: "Quiz & Candy Reward",
              shape: "cone",
              position: [0, -2.0, 0.5],
              scale: [0.9, 0.9, 0.9],
              color: "#f43f5e",
              animation: "float",
              tooltip: "Mastery verification & Candy reward engine",
            },
          ],
          connections: [
            {
              fromId: "pillar-1",
              toId: "core",
              color: "#38bdf8",
              animatedPacket: true,
              label: "Concept Input",
            },
            {
              fromId: "core",
              toId: "pillar-2",
              color: "#34d399",
              animatedPacket: true,
              label: "3D Synthesis",
            },
            {
              fromId: "core",
              toId: "pillar-3",
              color: "#f43f5e",
              animatedPacket: true,
              label: "Quiz Check",
            },
          ],
        },
      };

  return (
    <MentorStudioView
      mentor={mentor}
      standaloneTestMode={query.test === "true"}
    />
  );
}
